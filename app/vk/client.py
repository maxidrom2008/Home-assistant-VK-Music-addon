"""VK client boundary; concrete adapter will be added after API verification."""
from typing import Any, Protocol

class VKClient(Protocol):
    async def validate(self) -> bool: ...
    async def list_my_tracks(self, *, limit: int, offset: int) -> list[dict[str, Any]]: ...
    async def search_tracks(self, query: str, *, limit: int, offset: int) -> list[dict[str, Any]]: ...
    async def get_stream_url(self, track_id: str) -> str: ...

class VKNotConfiguredError(RuntimeError):
    """Raised when no authenticated VK adapter is configured."""
